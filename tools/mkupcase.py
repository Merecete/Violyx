#!/usr/bin/env python3
"""Creates the exFAT up-case table for the formatter: every character of the Basic Multilingual
Plane that has a simple, reversible capital letter maps to it. Runs of unchanged characters are
compressed as the exFAT specification describes (0xFFFF, count), from 0x80 on like the
recommended table. Usage: mkupcase.py OUT.h"""

import sys


def upper(c):
    if 0xD800 <= c < 0xE000:
        return c
    u = chr(c).upper()
    if len(u) != 1 or ord(u) == c or u.lower() != chr(c):
        return c
    return ord(u)


out = []
c = 0
while c < 0x10000:
    if upper(c) == c and c >= 0x80:  # the first 128 entries are written out in full
        n = 0
        while c + n < 0x10000 and upper(c + n) == c + n:
            n += 1
        if n > 2:
            out += [0xFFFF, n]
            c += n
            continue
    out.append(upper(c))
    c += 1
data = b"".join(v.to_bytes(2, "little") for v in out)
with open(sys.argv[1], "w") as f:
    f.write("/* exFAT up-case table, compressed. Generated by tools/mkupcase.py */\n")
    f.write("static const unsigned char upcase_tab[%d] = {\n" % len(data))
    for i in range(0, len(data), 16):
        f.write("    " + ", ".join("0x%02X" % b for b in data[i : i + 16]) + ",\n")
    f.write("};\n")
