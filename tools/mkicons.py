def _gemfall():
    """Gemfall: a column of three gems falls into the well, a row of gems lies at the bottom."""
    g = [["."] * 24 for _ in range(24)]
    shape = ["..kkkk..", ".kAwBBk.", "kAABBBBk", "kBBBBBCk", ".kBBBCk.", "..kBCk..", "...kk..."]

    def gem(x, y, a, b, c):
        for dy, row in enumerate(shape):
            for dx, ch in enumerate(row):
                if ch != ".":
                    g[y + dy][x + dx] = {"A": a, "B": b, "C": c}.get(ch, ch)

    gem(8, 1, "L", "H", "h")    # pink
    gem(8, 8, "C", "c", "b")    # cyan
    for y in (2, 3, 5, 6, 9, 10, 12):  # it falls: lines beside it
        g[y][5] = g[y][18] = "P"
    for k, (a, b, c) in enumerate([("Y", "y", "o"), ("l", "p", "V"), ("n", "n", "N")]):
        gem(k * 8, 17, a, b, c)
    return "\n" + "\n".join("".join(r) for r in g) + "\n"


ICONS["gemfall"] = _gemfall()

