def check():
    for n, a in ICONS.items():
        rows = a.strip("\n").split("\n")
        if len(rows) != 24 or any(len(r) != 24 for r in rows):
            raise SystemExit(f"{n}: must be 24 lines of 24 letters, " + str([len(r) for r in rows]))
        for r in rows:
            for c in r:
                if c not in COL:
                    raise SystemExit(f"{n}: unknown colour letter {c!r}")


def pixels(name):
    return [COL[c] for r in ICONS[name].strip("\n").split("\n") for c in r]


def rgb(i):
    L = [0, 95, 135, 175, 215, 255]
    if i < 232:
        i -= 16
        return (L[i // 36], L[i // 6 % 6], L[i % 6])
    g = 8 + 10 * (i - 232)
    return (g, g, g)


def png(path, px):
    raw = b""
    for y in range(24):
        raw += b"\0"
        for x in range(24):
            i = px[y * 24 + x]
            raw += bytes(rgb(i) + (255,)) if i else b"\0\0\0\0"

    def chunk(t, d):
        return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)

    open(path, "wb").write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", 24, 24, 8, 6, 0, 0, 0))
                           + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


BUILTIN = ["write", "internet", "files", "commands", "calc", "calendar", "clock", "voice", "paint",
           "pong", "invaders", "chomp", "mines", "snake", "bricks", "novastrike", "settings",
           "sysinfo", "help"]

if __name__ == "__main__":
    check()
    hdr, folder = sys.argv[1], sys.argv[2]
    with open(hdr, "w") as f:
        f.write("/* Program icons, 24x24 pixels in 256 colours, 0 is transparent. Made by tools/mkicons.py\n"
                " * from the drawings there, (c) 2026 Merecete (BSD-3-Clause) */\n")
        for n in BUILTIN:
            p = pixels(n)
            f.write(f"static const unsigned char icon_{n}[576] = {{\n")
            for y in range(24):
                f.write("    " + ", ".join(str(v) for v in p[y * 24:y * 24 + 24]) + ",\n")
            f.write("};\n")
    os.makedirs(folder, exist_ok=True)
    for n in ICONS:
        png(os.path.join(folder, n + ".png"), pixels(n))
